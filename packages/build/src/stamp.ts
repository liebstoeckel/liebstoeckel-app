// The built deck's provenance stamp and the checks on a deck's own plugin
// declarations: plain functions over strings.
import type { DeckLocalPlugin } from "@liebstoeckel/plugin-sdk/discovery";

/** Identifies the tool that drove the build (e.g. the CLI), stamped alongside the
 *  engine version so a built deck records what produced it. */
export interface Generator {
  name: string;
  version: string;
}

/** The engine version a bundle actually loaded, from the per-package versions;
 *  null when the deck bundles no engine (or more than one, which the build refuses). */
export function bundledEngineVersion(versions: Map<string, string[]>): string | null {
  const found = versions.get("@liebstoeckel/engine");
  return found && found.length === 1 ? found[0]! : null;
}

/** Stamp the build's provenance into the document head: a comment right after the
 *  doctype (the first thing in "view source") and a `<meta name="generator">` that
 *  tooling can parse (relays read it to know what a file contains). Versions only,
 *  no timestamp, so the same deck builds to the same bytes. */
export function stampGenerator(html: string, parts: { engine: string; generator?: Generator }): string {
  const tools = [`engine ${parts.engine}`];
  if (parts.generator) tools.push(`${parts.generator.name} ${parts.generator.version}`);
  const summary = `liebstoeckel ${tools.join(", ")}`;
  return html
    .replace(/<!doctype html>/i, (m) => `${m}\n<!-- Generated by ${summary} · https://liebstoeckel.app -->`)
    .replace(/<head[^>]*>/i, (m) => `${m}\n    <meta name="generator" content="${summary}" />`);
}

const escapeRe = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** Warnings for the audience fields a deck declares for its own plugins
 *  (`liebstoeckel.plugins` in package.json) that its source does not seem to back:
 *  no loaded deck file defines a plugin with that id, or none has a state field of
 *  that name. A text check, so it can miss unusual code, but it catches the typo
 *  that would silently drop every audience vote. */
export function deckPluginWarnings(declared: DeckLocalPlugin[], files: Array<{ path: string; text: string }>): string[] {
  const warnings: string[] = [];
  for (const p of declared) {
    const idRe = new RegExp(`\\bid\\s*:\\s*(["'\`])${escapeRe(p.id)}\\1`);
    const defining = files.filter((f) => idRe.test(f.text));
    if (defining.length === 0) {
      warnings.push(
        `⚠ package.json declares audience fields for plugin "${p.id}", but no deck file defines a plugin with that id: ` +
          `the audience's writes to it would be refused on a relay`,
      );
      continue;
    }
    for (const field of p.audienceWrites) {
      const fieldRe = new RegExp(`(^|[\\s{,])(["']?)${escapeRe(field)}\\2\\s*:`, "m");
      if (!files.some((f) => fieldRe.test(f.text))) {
        warnings.push(
          `⚠ package.json lets the audience write "${field}" of plugin "${p.id}" (defined in ${defining.map((f) => f.path).join(", ")}), ` +
            `but no deck file has a state field of that name`,
        );
      }
    }
  }
  return warnings;
}
